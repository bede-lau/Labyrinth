const WRONG: unknown[] = [null, 'x', '', 0, 1, 2, 1.5, -1, true, false, [], {}, [1], { a: 1 }, 'live', 'n/a'];
const clone = <T>(v: T): T => JSON.parse(JSON.stringify(v)) as T;

/** Every single-step corruption of `base`: [where/what, corrupted copy]. */
function corruptions(base: unknown): [string, unknown][] {
  const out: [string, unknown][] = [];
  const visit = (node: unknown, path: (string | number)[]) => {
    const at = (fn: (parent: Record<string | number, unknown>, key: string | number) => void, what: string) => {
      const copy = clone(base) as Record<string | number, unknown>;
      if (path.length === 0) return; // the root is replaced separately
      let parent = copy;
      for (const k of path.slice(0, -1)) parent = parent[k] as Record<string | number, unknown>;
      fn(parent, path[path.length - 1] as string | number);
      out.push([`${path.join('.')}: ${what}`, copy]);
    };
    for (const w of WRONG) {
      if (JSON.stringify(w) === JSON.stringify(node)) continue;
      at((p, k) => (p[k] = w), `= ${JSON.stringify(w)}`);
    }
    if (Array.isArray(node)) {
      at((p, k) => (p[k] = [...(p[k] as unknown[]), ...(p[k] as unknown[]), ...(p[k] as unknown[])]), 'tripled');
      node.forEach((child, i) => visit(child, [...path, i]));
    } else if (typeof node === 'object' && node !== null) {
      at((p, k) => ((p[k] as Record<string, unknown>).unexpected = 1), 'extra key');
      for (const key of Object.keys(node)) {
        at((p, k) => delete (p[k] as Record<string, unknown>)[key], `without ${key}`);
        visit((node as Record<string, unknown>)[key], [...path, key]);
      }
    }
  };
  // Root level: wrong types, a missing key, an extra key.
  for (const w of WRONG) out.push([`$ = ${JSON.stringify(w)}`, w]);
  if (typeof base === 'object' && base !== null) {
    for (const key of Object.keys(base)) {
      const copy = clone(base) as Record<string, unknown>;
      delete copy[key];
      out.push([`$ without ${key}`, copy]);
      visit((base as Record<string, unknown>)[key], [key]);
    }
    out.push(['$ extra key', { ...(clone(base) as object), unexpected: 1 }]);
  }
  return out;
}

test('validateLiveStatus agrees with contracts/live-status.schema.json on valid snapshots and on every corruption of them', () => {
  const a = ajv();
  const oracle = (doc: unknown) => a.validate('live-status.schema.json', doc) as boolean;
  for (const base of [idle, live, fallback]) {
    expect(oracle(base), JSON.stringify(a.errors)).toBe(true);
    expect(validateLiveStatus(base)).toBeNull();
  }
  // Every mode of the contract is accepted, and the list in the code is the list in the schema.
  expect([...LIVE_MODES]).toEqual(schema('live-status.schema.json').properties.mode.enum);
  for (const mode of LIVE_MODES) expect(validateLiveStatus({ ...idle, mode })).toBeNull();

  const corpus = [idle, live, fallback].flatMap((b) => corruptions(b));
  const disagreements: string[] = [];
  let rejected = 0;
  for (const [what, doc] of corpus) {
    const expected = oracle(doc);
    const problem = validateLiveStatus(doc);
    if (!expected) rejected += 1;
    if ((problem === null) !== expected) disagreements.push(`${what}: schema says ${expected ? 'valid' : 'invalid'}, validator says ${problem ?? 'valid'}`);
  }
  expect(disagreements).toEqual([]);
  // The corpus is not vacuous: most corruptions are invalid, a few (e.g. another valid enum value) stay valid.
  expect(corpus.length).toBeGreaterThan(900);
  expect(rejected).toBeGreaterThan(700);
  expect(corpus.length - rejected).toBeGreaterThan(20);
});

