// @vitest-environment node
// The hand-written validators in liveContract.ts must agree with the real JSON Schemas in
// ../contracts. ajv (a dev dependency) is the oracle here; the app itself ships no schema library.
// A corpus of broken payloads is generated from valid ones (a key removed, a wrong type, an extra
// key, a list too long …) and every verdict is compared.
import Ajv2020 from 'ajv/dist/2020';
import { readFileSync, readdirSync } from 'node:fs';
import { resolve } from 'node:path';
import { LIVE_MODES, SAVED_RUN_ID, validateLiveStatus, validateSavedRun, type LiveStatus, type SavedRun } from './liveContract';

const CONTRACTS = resolve(__dirname, '../../../contracts');
const schema = (file: string) => JSON.parse(readFileSync(resolve(CONTRACTS, file), 'utf8'));

function ajv() {
  const a = new Ajv2020({ allErrors: true, strict: false });
  for (const f of readdirSync(CONTRACTS).filter((f) => f.endsWith('.schema.json'))) a.addSchema(schema(f), f);
  return a;
}

